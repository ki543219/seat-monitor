# Builds src/ca_bundle.h: root CAs trusted for the HTTPS uploads to Supabase.
# Supabase (Cloudflare) currently chains WE1 -> GTS Root R4 (also cross-signed by GlobalSign
# Root CA). The other roots are included so a CA switch on their side does not break uploads.
# GTS roots come from Google's PKI repository; the rest from the Windows trust store.
# Usage: powershell -File tools/make_ca_bundle.ps1
$ErrorActionPreference = 'Stop'
$entries = @()
foreach ($r in 'r1', 'r4') {
  $pem = (Invoke-WebRequest -UseBasicParsing "https://i.pki.goog/$r.pem").Content
  if ($pem -is [byte[]]) { $pem = [Text.Encoding]::ASCII.GetString($pem) }
  $cert = [Security.Cryptography.X509Certificates.X509Certificate2]::new([Text.Encoding]::ASCII.GetBytes($pem))
  $entries += [pscustomobject]@{ Name = $cert.Subject; Expires = $cert.NotAfter; Der = $cert.RawData }
}
# GitHub (OTA release check) chains to USERTrust; release downloads to ISRG Root X1.
foreach ($n in 'CN=GlobalSign Root CA, OU=Root CA, O=GlobalSign nv-sa, C=BE',
               'CN=ISRG Root X1, O=Internet Security Research Group, C=US',
               'CN=USERTrust ECC Certification Authority, O=The USERTRUST Network, L=Jersey City, S=New Jersey, C=US',
               'CN=USERTrust RSA Certification Authority, O=The USERTRUST Network, L=Jersey City, S=New Jersey, C=US') {
  $c = Get-ChildItem Cert:\LocalMachine\Root, Cert:\CurrentUser\Root | Where-Object Subject -eq $n | Select-Object -First 1
  if (-not $c) { throw "missing root in Windows store: $n" }
  $entries += [pscustomobject]@{ Name = $c.Subject; Expires = $c.NotAfter; Der = $c.RawData }
}
$lines = @('#pragma once', '// Generated by tools/make_ca_bundle.ps1. Root CAs trusted for HTTPS uploads.',
           'static const char kCaBundle[] =')
foreach ($e in $entries) {
  $lines += "    // $($e.Name) (expires $($e.Expires.ToString('yyyy-MM-dd')))"
  $lines += '    "-----BEGIN CERTIFICATE-----\n"'
  foreach ($chunk in ([Convert]::ToBase64String($e.Der) -split '(.{64})' | Where-Object { $_ })) { $lines += "    `"$chunk\n`"" }
  $lines += '    "-----END CERTIFICATE-----\n"'
}
$lines[-1] += ';'
Set-Content -Path src/ca_bundle.h -Value ($lines -join "`n") -Encoding ascii
"wrote src/ca_bundle.h ($($entries.Count) roots)"
