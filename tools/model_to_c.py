"""Convert a .tflite file into a C++ source file that embeds it as an aligned byte array.

Usage: python tools/model_to_c.py tools/person_detect.tflite src/model_data.cpp
"""
import sys
from pathlib import Path


def main(src: str, dst: str) -> None:
    data = Path(src).read_bytes()
    if data[4:8] != b"TFL3":
        sys.exit(f"{src} is not a TFLite flatbuffer")
    rows = [
        "  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ","
        for i in range(0, len(data), 16)
    ]
    out = "\n".join(
        [
            f"// Generated by tools/model_to_c.py from {Path(src).name}. Do not edit.",
            '#include "model_data.h"',
            "",
            "alignas(16) const unsigned char g_model_data[] = {",
            *rows,
            "};",
            f"const unsigned int g_model_data_len = {len(data)};",
            "",
        ]
    )
    Path(dst).write_text(out, encoding="ascii", newline="\n")
    print(f"wrote {dst} ({len(data)} bytes)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
